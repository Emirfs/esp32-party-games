#pragma once

// The room: profiles, lobby, admin and the running game. All protocol
// messages except hello/ping end up here (Hub forwards them). Single-threaded:
// on the box every call happens on the httpd task.

#include <cstddef>
#include <cstdint>
#include <memory>
#include <string>
#include <vector>

#include "game.h"
#include "json.h"
#include "rng.h"
#include "store.h"

// What the room needs from the device. Firmware: wifi_ap + esp_restart;
// host simulator: fixed values.
class Platform {
 public:
  virtual ~Platform() = default;
  virtual const char* ssid() const = 0;
  // Wi-Fi password the AP is running with right now.
  virtual const char* wifiPassword() const = 0;
  // Reboots the box (admin "restart", e.g. to apply a new Wi-Fi password).
  virtual void restart() = 0;
};

constexpr size_t kClientIdMax = 23;  // [A-Za-z0-9_-]{1,23}, generated by the phone
constexpr size_t kNameMax = 48;      // bytes of UTF-8, at most 16 characters
constexpr size_t kAvatarMax = 16;    // bytes of UTF-8 (one emoji, possibly with modifiers)
constexpr int kColors = 12;
constexpr size_t kKnownProfiles = 32;  // remembered phones (LRU)
constexpr size_t kWifiPassMin = 8;
constexpr size_t kWifiPassMax = 63;
// Store key of the admin-set Wi-Fi password (NUL-terminated); read by the
// firmware at boot.
constexpr char kKeyWifiPass[] = "wifi_pass";

bool validClientId(const char* id);

struct Profile {
  char id[kClientIdMax + 1];
  char name[kNameMax + 1];
  char avatar[kAvatarMax + 1];
  uint8_t color;
  uint16_t played;
  uint16_t won;
  uint32_t lastUse;  // LRU counter
};

class Room : private GameHost {
 public:
  Room(Store& store, Platform& platform, uint64_t seed);
  ~Room() override;

  // Loads profiles, admin and the snapshot (lobby + running game) from the store.
  void begin(uint32_t now);

  // Hub events. `clientId` has already been validated.
  void connected(const char* clientId, uint32_t now);
  void disconnected(const char* clientId, uint32_t now);
  // Any message other than hello/ping. Errors are queued as {"t":"err"} to the sender.
  void handle(const char* clientId, const json::Value& msg, uint32_t now);
  void tick(uint32_t now);

  // Holding BOOT for 5 s: the box has no admin until someone claims it again.
  void resetAdmin();

  // Bumped on every change any phone could see; Hub re-sends views when it moves.
  uint32_t version() const { return version_; }
  // {"t":"view","seq":<version>,"view":{...}} for this phone (docs/protocol.md).
  void renderView(const char* clientId, uint32_t now, std::string& out) const;

  struct Outgoing {
    std::string clientId;
    std::string text;
  };
  // One-off messages (err, buzz) queued since the last call.
  std::vector<Outgoing> takeOutbox();

 private:
  struct Member {
    bool used = false;
    bool online = false;
    bool ready = false;
    char id[kClientIdMax + 1] = {};
  };

  // GameHost
  Rng& rng() override { return rng_; }
  void setTimer(uint32_t ms) override;
  void phaseChanged() override;
  void buzz(PlayerMask players, const char* pattern) override;
  bool online(int pid) const override;

  int pidOf(const char* clientId) const;
  Profile* profileOf(const char* clientId);
  const Profile* profileOf(const char* clientId) const;
  bool isAdmin(const char* clientId) const;
  int adminPid() const;
  int freeSlot() const;
  bool join(const char* clientId);
  void error(const char* clientId, const char* code);
  void changed() { ++version_; }
  void afterGameStep();
  void snapshot();

  const char* onProfile(const char* clientId, const json::Value& msg);
  const char* onReady(const char* clientId, const json::Value& msg);
  const char* onClaimAdmin(const char* clientId);
  const char* onTransfer(const char* clientId, const json::Value& msg);
  const char* onKick(const char* clientId, const json::Value& msg);
  const char* onSettings(const char* clientId, const json::Value& msg);
  const char* onStart(const char* clientId, const json::Value& msg);
  const char* onEnd(const char* clientId);

  void saveProfiles();
  void saveRoom();
  void saveGame();
  void renderPlayers(json::Writer& w) const;

  Store& store_;
  Platform& platform_;
  Rng rng_;
  uint32_t now_ = 0;
  uint32_t version_ = 1;

  Profile profiles_[kKnownProfiles] = {};
  uint32_t lruClock_ = 0;
  Member members_[kMaxPlayers];
  char admin_[kClientIdMax + 1] = {};

  std::unique_ptr<Game> game_;
  PlayerMask seated_ = 0;
  bool statsDone_ = false;
  uint32_t deadline_ = 0;  // 0 = no timer
  bool snapshotDue_ = false;

  std::vector<Outgoing> outbox_;
};
